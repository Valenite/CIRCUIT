// Resistor EIA color code helper
export function getResistorBands(resistance: number): string[] {
  const COLOR_MAP: Record<number, string> = {
    0: '#000000', // Black
    1: '#854d0e', // Brown
    2: '#dc2626', // Red
    3: '#ea580c', // Orange
    4: '#eab308', // Yellow
    5: '#16a34a', // Green
    6: '#2563eb', // Blue
    7: '#7c3aed', // Violet
    8: '#6b7280', // Grey
    9: '#ffffff', // White
  };

  if (!resistance || resistance <= 0) {
    return ['#000000', '#000000', '#000000', '#d97706'];
  }

  const str = Math.round(resistance).toString();
  const d1 = parseInt(str[0], 10) || 0;
  const d2 = parseInt(str[1], 10) || 0;
  const multiplier = str.length - 2;

  const band1 = COLOR_MAP[d1] || '#854d0e';
  const band2 = COLOR_MAP[d2] || '#000000';
  const band3 = COLOR_MAP[Math.max(0, multiplier)] || '#dc2626';
  const tolerance = '#d97706'; // Gold 5%

  return [band1, band2, band3, tolerance];
}
